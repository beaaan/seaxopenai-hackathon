/**
 * Codex App Server backend: one long-lived `codex app-server` process (stdio JSONL,
 * JSON-RPC without the "jsonrpc" header), many concurrent threads.
 *
 * - structured(): ephemeral thread + one turn with `outputSchema`.
 * - agentThread(): thread with client-side `dynamicTools`; `item/tool/call` server
 *   requests are answered by our ToolDef handlers.
 * `baseInstructions` replaces the Codex coding persona entirely; threads run read-only
 * with approvalPolicy "never". The process runs in an empty working directory with
 * every built-in tool family disabled (ISOLATION_OVERRIDES), so a persona or reviewer
 * sees only the evidence we send and the dynamic tools we register — never the repo,
 * the reference answers or the holdout. Wire shapes: vendor/codex-app-server
 * (generated by `npm run codex:types`).
 */
import { spawn, type ChildProcessWithoutNullStreams } from "node:child_process";
import { mkdirSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { createInterface } from "node:readline";
import type { DynamicToolCallParams } from "../../../vendor/codex-app-server/v2/DynamicToolCallParams";
import type { DynamicToolCallResponse } from "../../../vendor/codex-app-server/v2/DynamicToolCallResponse";
import type { DynamicToolSpec } from "../../../vendor/codex-app-server/v2/DynamicToolSpec";
import type { ItemCompletedNotification } from "../../../vendor/codex-app-server/v2/ItemCompletedNotification";
import type { ThreadStartParams } from "../../../vendor/codex-app-server/v2/ThreadStartParams";
import type { ThreadTokenUsageUpdatedNotification } from "../../../vendor/codex-app-server/v2/ThreadTokenUsageUpdatedNotification";
import type { TokenUsageBreakdown } from "../../../vendor/codex-app-server/v2/TokenUsageBreakdown";
import type { TurnCompletedNotification } from "../../../vendor/codex-app-server/v2/TurnCompletedNotification";
import type { TurnStartParams } from "../../../vendor/codex-app-server/v2/TurnStartParams";
import { config } from "../env";
import { llmJsonSchema } from "./json-schema";
import { Limiter } from "./limit";
import type { AgentThread, AgentThreadOptions, Effort, LlmBackend, OutputSchema, StructuredRequest, ToolDef, TurnResult } from "./types";
import { logUsage, type UsageStage } from "./usage";

/** `dynamicTools` is experimental and missing from the generated ThreadStartParams. */
type ThreadStart = ThreadStartParams & { dynamicTools?: DynamicToolSpec[] };

const REQUEST_TIMEOUT_MS = 60_000;

/** `codex -c` overrides that strip every built-in capability; only our dynamic tools remain. */
const ISOLATION_OVERRIDES = [
  ...[
    "shell_tool", "unified_exec", "multi_agent", "apps", "plugins", "image_generation", "computer_use",
    "browser_use", "browser_use_external", "in_app_browser", "view_image", "skill_search", "tool_suggest",
    "goals", "hooks", "sleep_tool",
  ].flatMap((feature) => ["-c", `features.${feature}=false`]),
  "-c", "web_search=disabled",
  "-c", "project_doc_max_bytes=0",
  "-c", "mcp_servers={}",
];

/** Reads one field of an untrusted JSON value. */
function field(value: unknown, key: string): unknown {
  return typeof value === "object" && value !== null ? Reflect.get(value, key) : undefined;
}

interface RpcMessage {
  id?: number | string;
  method?: string;
  params?: unknown;
  result?: unknown;
  error?: { code: number; message: string };
}

interface Pending {
  method: string;
  resolve: (value: unknown) => void;
  reject: (err: Error) => void;
}

interface ThreadState {
  tools: readonly ToolDef[];
  model: string;
  stage: UsageStage;
  tokenUsage: TokenUsageBreakdown | null;
  onNotification: ((method: string, params: unknown) => void) | null;
  /** Settles when the thread's current turn ends; turns on one thread run one at a time. */
  tail: Promise<void>;
}

export interface AppServerOptions {
  /** Executable; default `codex` (PWT_CODEX_COMMAND). */
  command: string;
  args: string[];
  cwd?: string;
  concurrency: number;
  turnTimeoutMs: number;
  /** Spawn through a shell; needed on Windows where `codex` is a .cmd shim. */
  shell: boolean;
}

export class AppServerBackend implements LlmBackend {
  readonly name = "appserver" as const;
  readonly #opts: AppServerOptions;
  readonly #limiter: Limiter;
  readonly #pending = new Map<number | string, Pending>();
  readonly #threads = new Map<string, ThreadState>();
  #proc: ChildProcessWithoutNullStreams | null = null;
  #ready: Promise<void> | null = null;
  #nextId = 1;
  #stderrTail = "";

  constructor(opts: AppServerOptions) {
    this.#opts = opts;
    this.#limiter = new Limiter(opts.concurrency);
  }

  static fromConfig(): AppServerBackend {
    const cwd = join(tmpdir(), "pwt-appserver-empty");
    mkdirSync(cwd, { recursive: true });
    return new AppServerBackend({
      command: config.codexCommand,
      args: [...ISOLATION_OVERRIDES, "app-server"],
      cwd,
      concurrency: config.appServerConcurrency,
      turnTimeoutMs: config.turnTimeoutMs,
      shell: process.platform === "win32",
    });
  }

  // -------------------------------------------------------------------------
  // transport

  #start(): Promise<void> {
    if (this.#ready) return this.#ready;
    // Default stdio is all pipes. With a shell, pass one command line (fixed literals only).
    const proc = this.#opts.shell
      ? spawn([this.#opts.command, ...this.#opts.args].join(" "), { cwd: this.#opts.cwd, shell: true })
      : spawn(this.#opts.command, this.#opts.args, { cwd: this.#opts.cwd });
    this.#proc = proc;
    proc.stderr.on("data", (chunk: Buffer) => {
      this.#stderrTail = (this.#stderrTail + chunk.toString("utf8")).slice(-4000);
    });
    proc.on("exit", (code, signal) => this.#failAll(new Error(`codex app-server exited (${code ?? signal}): ${this.#stderrTail.slice(-800)}`)));
    proc.on("error", (err) => this.#failAll(err));
    createInterface({ input: proc.stdout }).on("line", (line) => this.#onLine(line));

    this.#ready = (async () => {
      await this.#request("initialize", {
        clientInfo: { name: "policy_wind_tunnel", title: "Policy Wind Tunnel", version: "0.1.0" },
        capabilities: { experimentalApi: true },
      });
      this.#send({ method: "initialized", params: {} });
    })();
    return this.#ready;
  }

  /** Drops the message when the transport is gone (e.g. a tool finishing after close). */
  #send(message: RpcMessage): void {
    this.#proc?.stdin.write(`${JSON.stringify(message)}\n`);
  }

  #request(method: string, params: unknown, timeoutMs = REQUEST_TIMEOUT_MS): Promise<unknown> {
    if (!this.#proc) return Promise.reject(new Error(`app-server not started (${method})`));
    const id = this.#nextId++;
    const { promise, resolve, reject } = Promise.withResolvers<unknown>();
    const timer = setTimeout(() => {
      this.#pending.delete(id);
      reject(new Error(`${method}: no response after ${timeoutMs} ms`));
    }, timeoutMs);
    this.#pending.set(id, {
      method,
      resolve: (value) => { clearTimeout(timer); resolve(value); },
      reject: (err) => { clearTimeout(timer); reject(err); },
    });
    this.#send({ id, method, params });
    return promise;
  }

  #failAll(err: Error): void {
    for (const pending of this.#pending.values()) pending.reject(err);
    this.#pending.clear();
    for (const thread of this.#threads.values()) thread.onNotification?.("pwt/transportError", { message: err.message });
    this.#proc = null;
    this.#ready = null;
  }

  #onLine(line: string): void {
    let msg: RpcMessage;
    try {
      msg = JSON.parse(line) as RpcMessage;
    } catch {
      return; // not protocol output
    }
    if (msg.id !== undefined && msg.method !== undefined) {
      this.#onServerRequest(msg.id, msg.method, msg.params).catch(() => {});
      return;
    }
    if (msg.id !== undefined) {
      const pending = this.#pending.get(msg.id);
      if (!pending) return;
      this.#pending.delete(msg.id);
      if (msg.error) pending.reject(new Error(`${pending.method}: ${msg.error.message} (${msg.error.code})`));
      else pending.resolve(msg.result);
      return;
    }
    if (msg.method !== undefined) {
      const threadId = field(msg.params, "threadId");
      if (typeof threadId === "string") this.#threads.get(threadId)?.onNotification?.(msg.method, msg.params);
    }
  }

  async #onServerRequest(id: number | string, method: string, params: unknown): Promise<void> {
    if (method !== "item/tool/call") {
      this.#send({ id, error: { code: -32601, message: `policy_wind_tunnel does not handle ${method}` } });
      return;
    }
    const call = params as DynamicToolCallParams;
    const tool = this.#threads.get(call.threadId)?.tools.find((t) => t.name === call.tool);
    let response: DynamicToolCallResponse;
    if (!tool) {
      response = { contentItems: [{ type: "inputText", text: JSON.stringify({ error: `unknown tool: ${call.tool}` }) }], success: false };
    } else {
      try {
        const result = await tool.handler(tool.input.parse(call.arguments));
        response = { contentItems: [{ type: "inputText", text: JSON.stringify(result) }], success: true };
      } catch (err) {
        response = { contentItems: [{ type: "inputText", text: JSON.stringify({ error: (err as Error).message }) }], success: false };
      }
    }
    this.#send({ id, result: response });
  }

  // -------------------------------------------------------------------------
  // threads and turns

  async #startThread(params: ThreadStart, tools: readonly ToolDef[], stage: UsageStage): Promise<string> {
    await this.#start();
    const result = (await this.#request("thread/start", { ...params, cwd: this.#opts.cwd ?? null })) as { thread: { id: string } };
    this.#threads.set(result.thread.id, { tools, model: params.model ?? "unknown", stage, tokenUsage: null, onNotification: null, tail: Promise.resolve() });
    return result.thread.id;
  }

  async #runTurn(
    threadId: string,
    input: string,
    effort: Effort,
    outputSchema: OutputSchema | undefined,
    onItem: ((itemType: string, item: unknown) => void) | undefined,
  ): Promise<TurnResult> {
    const state = this.#threads.get(threadId);
    if (!state) throw new Error(`unknown thread ${threadId}`);
    const previous = state.tail;
    const { promise: done, resolve: release } = Promise.withResolvers<void>();
    state.tail = done;
    await previous;
    try {
      return await this.#turnOnce(state, threadId, input, effort, outputSchema, onItem);
    } finally {
      release();
    }
  }

  async #turnOnce(
    state: ThreadState,
    threadId: string,
    input: string,
    effort: Effort,
    outputSchema: OutputSchema | undefined,
    onItem: ((itemType: string, item: unknown) => void) | undefined,
  ): Promise<TurnResult> {
    const items: unknown[] = [];
    let finalText = "";
    let errorMessage: string | null = null;
    let turnId: string | null = null;
    const previousUsage = state.tokenUsage;
    let usage: TokenUsageBreakdown | null = null;
    const { promise, resolve, reject } = Promise.withResolvers<TurnResult>();
    // Awaited below; this handler only keeps an early rejection (transport failure while
    // turn/start is pending) from surfacing as unhandled.
    promise.catch(() => {});

    state.onNotification = (method, params) => {
      const notificationTurn = field(params, "turnId") ?? field(field(params, "turn"), "id");
      if (turnId !== null && typeof notificationTurn === "string" && notificationTurn !== turnId) return;
      if (method === "thread/tokenUsage/updated") {
        usage = (params as ThreadTokenUsageUpdatedNotification).tokenUsage.total;
        state.tokenUsage = usage;
      } else if (method === "item/completed") {
        const { item } = params as ItemCompletedNotification;
        items.push(item);
        onItem?.(item.type, item);
        if (item.type === "agentMessage") finalText = item.text;
      } else if (method === "error") {
        errorMessage = JSON.stringify(field(params, "error") ?? params);
      } else if (method === "turn/completed") {
        const { turn } = params as TurnCompletedNotification;
        if (turn.status === "completed") resolve({ threadId, finalText, items });
        else reject(new Error(`turn ${turn.status}: ${JSON.stringify(turn.error) ?? errorMessage ?? "no error detail"}`));
      } else if (method === "pwt/transportError") {
        reject(new Error(String(field(params, "message"))));
      }
    };

    const timer = setTimeout(() => {
      reject(new Error(`turn timed out after ${this.#opts.turnTimeoutMs} ms`));
      if (turnId) this.#request("turn/interrupt", { threadId, turnId }).catch(() => {});
    }, this.#opts.turnTimeoutMs);

    try {
      const params: TurnStartParams = {
        threadId,
        input: [{ type: "text", text: input, text_elements: [] }],
        effort,
        outputSchema: outputSchema ? llmJsonSchema(outputSchema.schema) : null,
      };
      const started = (await this.#request("turn/start", params)) as { turn: { id: string } };
      turnId = started.turn.id;
      return await promise;
    } finally {
      clearTimeout(timer);
      state.onNotification = null;
      if (turnId !== null) {
        const measured = usage as TokenUsageBreakdown | null;
        logUsage({
          backend: "appserver", model: state.model, stage: state.stage,
          inputTokens: measured === null ? null : measured.inputTokens - (previousUsage?.inputTokens ?? 0),
          cachedInputTokens: measured === null ? null : measured.cachedInputTokens - (previousUsage?.cachedInputTokens ?? 0),
          outputTokens: measured === null ? null : measured.outputTokens - (previousUsage?.outputTokens ?? 0),
          reasoningTokens: measured === null ? null : measured.reasoningOutputTokens - (previousUsage?.reasoningOutputTokens ?? 0),
        });
      }
    }
  }

  async #dropThread(threadId: string): Promise<void> {
    this.#threads.delete(threadId);
    await this.#request("thread/unsubscribe", { threadId }).catch(() => {});
  }

  structured<T>(req: StructuredRequest<T>): Promise<T> {
    return this.#limiter.run(async () => {
      const threadId = await this.#startThread(
        {
          model: req.model,
          ephemeral: true,
          approvalPolicy: "never",
          sandbox: "read-only",
          baseInstructions: req.instructions,
          serviceName: "policy_wind_tunnel",
        },
        [],
        req.stage ?? "other",
      );
      try {
        const result = await this.#runTurn(threadId, req.input, req.effort, { schema: req.schema, name: req.schemaName }, undefined);
        return req.schema.parse(JSON.parse(result.finalText));
      } finally {
        await this.#dropThread(threadId);
      }
    });
  }

  async agentThread(opts: AgentThreadOptions): Promise<AgentThread> {
    const threadId = await this.#startThread(
      {
        model: opts.model,
        ephemeral: !opts.persist,
        approvalPolicy: "never",
        sandbox: "read-only",
        baseInstructions: opts.instructions,
        serviceName: "policy_wind_tunnel",
        dynamicTools: opts.tools.map((t) => ({
          type: "function",
          name: t.name,
          description: t.description,
          inputSchema: llmJsonSchema(t.input),
        })),
      },
      opts.tools,
      opts.stage ?? "other",
    );
    const onItem = (itemType: string, item: unknown) =>
      opts.onItem?.({ threadId, role: opts.role, label: opts.label, backend: "appserver", itemType, item });
    return {
      threadId,
      turn: (input, output) => this.#limiter.run(() => this.#runTurn(threadId, input, opts.effort, output, onItem)),
      close: () => this.#dropThread(threadId),
    };
  }

  async close(): Promise<void> {
    const proc = this.#proc;
    if (!proc) return;
    proc.removeAllListeners("exit");
    this.#failAll(new Error("app-server closed"));
    this.#threads.clear();
    proc.kill();
  }
}
